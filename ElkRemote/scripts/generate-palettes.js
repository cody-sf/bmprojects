#!/usr/bin/env node
/**
 * Generate src/Palettes.h from RNUmbrella/constants.ts.
 *
 * Same idea as BMLightsWatch/scripts/generate-catalog.js: the app's palette
 * table is the single source of truth, and this file turns it into C so the
 * CYD remote cannot drift from what the phone shows. Re-run after changing
 * `palettes` in constants.ts, and check the result in.
 */
const fs = require('fs');
const path = require('path');

const constantsPath = path.join(__dirname, '..', '..', 'RNUmbrella', 'constants.ts');
const outPath = path.join(__dirname, '..', 'src', 'Palettes.h');

const src = fs.readFileSync(constantsPath, 'utf8');
const block = src.match(/export const palettes: Palettes = \{([\s\S]*?)\n\};/);
if (!block) {
  console.error('Could not find `export const palettes` in constants.ts');
  process.exit(1);
}

const entryRe = /(\w+):\s*\{\s*name:\s*'([^']*)',\s*palette:\s*\[([\s\S]*?)\]/g;
const palettes = [];
let m;
while ((m = entryRe.exec(block[1]))) {
  const colors = (m[3].match(/#[0-9a-fA-F]{6}/g) || []).map(hex => [
    parseInt(hex.slice(1, 3), 16),
    parseInt(hex.slice(3, 5), 16),
    parseInt(hex.slice(5, 7), 16),
  ]);
  if (!colors.length) continue;
  palettes.push({ key: m[1], name: m[2].trim(), colors });
}

if (!palettes.length) {
  console.error('Parsed zero palettes - constants.ts format changed?');
  process.exit(1);
}

const lines = [];
lines.push('// GENERATED by scripts/generate-palettes.js - do not edit.');
lines.push('// Source of truth: RNUmbrella/constants.ts `palettes`.');
lines.push('#pragma once');
lines.push('#include <stdint.h>');
lines.push('');
lines.push('struct PaletteDef {');
lines.push('  const char* key;');
lines.push('  const char* name;');
lines.push('  const uint8_t (*colors)[3];');
lines.push('  uint8_t count;');
lines.push('};');
lines.push('');
for (const p of palettes) {
  const rows = p.colors.map(c => `{${c[0]},${c[1]},${c[2]}}`).join(',');
  lines.push(`static const uint8_t PAL_${p.key}[][3] = {${rows}};`);
}
lines.push('');
lines.push('static const PaletteDef PALETTES[] = {');
for (const p of palettes) {
  lines.push(`  {"${p.key}", "${p.name}", PAL_${p.key}, ${p.colors.length}},`);
}
lines.push('};');
lines.push('');
lines.push(`static const uint8_t PALETTE_COUNT = ${palettes.length};`);
lines.push('');

fs.writeFileSync(outPath, lines.join('\n'));
console.log(`Wrote ${palettes.length} palettes to ${path.relative(process.cwd(), outPath)}`);
